import { writeFile } from "node:fs/promises";
import { FEEDS, feedUrl, parseFeed, mergeDiscoveries } from "./discovery-core.mjs";
import { DISCOVERY_ITEMS } from "../public/data/discovered.js";

const checkedAt = new Date();
const batches = [];
const failures = [];
for (const feed of FEEDS) {
  try {
    const controller = new AbortController();
    const timeout = setTimeout(() => controller.abort(), 12000);
    let response;
    try {
      response = await fetch(feedUrl(feed), { signal: controller.signal, headers: { "User-Agent": "Mozilla/5.0 (compatible; CSEPrepDesk/1.0; personal study index)", Accept: "application/rss+xml, application/xml;q=0.9, */*;q=0.8" } });
    } finally { clearTimeout(timeout); }
    if (!response.ok) throw new Error(`HTTP ${response.status}`);
    const xml = await response.text();
    if (xml.length > 2_000_000) throw new Error("Feed exceeds size limit");
    batches.push(parseFeed(xml, checkedAt));
  } catch (error) {
    failures.push(`${feed.language}:${feed.query.slice(0,30)}: ${error.message}`);
  }
}

if (!batches.length) {
  console.error("No RSS feed available; preserving last published circular discoveries.", failures);
  process.exitCode = 1;
} else {
  const today = checkedAt.toISOString().slice(0, 10);
  const jobs = mergeDiscoveries(DISCOVERY_ITEMS, batches, today);
  const source = `// Generated by scripts/update-circulars.mjs via the daily GitHub Actions workflow.\n` +
    `// These are third-party news-index leads ONLY, not verified official circulars or application deadlines.\n` +
    `export const DISCOVERY_LAST_RUN = ${JSON.stringify(checkedAt.toISOString())};\n` +
    `export const DISCOVERY_FEEDS_OK = ${batches.length};\n` +
    `export const DISCOVERY_FEEDS_TOTAL = ${FEEDS.length};\n` +
    `export const DISCOVERY_ITEMS = ${JSON.stringify(jobs, null, 2)};\n`;
  await writeFile(new URL("../public/data/discovered.js", import.meta.url), source, "utf8");
  console.log(`Discovery checked ${batches.length}/${FEEDS.length} feeds; ${jobs.length} candidate listings. ${failures.length} failures.`);
  if (failures.length) console.warn(failures.join("\n"));
}
